vim.keymap.set({ "n", "v", "i" }, "<Left>", "<Nop>")
vim.keymap.set({ "n", "v", "i" }, "<Right>", "<Nop>")

vim.api.nvim_create_autocmd("FileType", {
	pattern = "man",
	callback = function()
		vim.keymap.set("n", "F", "<cmd>lua require('man').show_toc()<CR>", { buffer = true, silent = true })
	end,
})

vim.keymap.set("v", ">", ">gv")
vim.keymap.set("v", "<", "<gv")
