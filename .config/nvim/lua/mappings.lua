vim.keymap.set("n", "N", "Nzzzv")
vim.keymap.set("n", "U", "<C-r>")
vim.keymap.set("n", "H", "^")
vim.keymap.set("n", "L", "$")
vim.keymap.set("i", "jj", "<Esc>")
vim.keymap.set({ "n", "v", "i" }, "<Up>", "<Nop>")
